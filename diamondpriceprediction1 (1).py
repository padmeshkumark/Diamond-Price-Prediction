import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder
from sklearn.linear_model import LinearRegression
from sklearn import metrics

diamond_dataset = pd.read_csv('/content/DiamondsPrices.csv')

print(diamond_dataset)

diamond_dataset.head()

diamond_dataset.tail()

diamond_dataset.shape

diamond_dataset.info()

diamond_dataset.isnull().sum()

diamond_dataset.tail(2)

diamond_dataset['price'].fillna(diamond_dataset['price'].mean(),inplace=True)
diamond_dataset['x'].fillna(diamond_dataset['x'].mean(),inplace= True)
diamond_dataset['y'].fillna(diamond_dataset['y'].mean(),inplace = True)
diamond_dataset['z'].fillna(diamond_dataset['z'].mean(),inplace = True)

print(diamond_dataset.cut.value_counts())
print(diamond_dataset.color.value_counts())
print(diamond_dataset.clarity.value_counts())

diamond_dataset.replace({'cut':{'Ideal':0,'Premium':1,'Very Good':2,'Good':3,'Fair':4}},inplace = True)

diamond_dataset

LE = LabelEncoder()
diamond_dataset['color'] = LE.fit_transform(diamond_dataset['color'])
diamond_dataset['clarity'] = LE.fit_transform(diamond_dataset['clarity'])

diamond_dataset

X = diamond_dataset.drop(['price'],axis=1)
Y = diamond_dataset['price']

X_train,X_test,Y_train,Y_test = train_test_split(X,Y,test_size=0.2,random_state=42)

model = LinearRegression()

model.fit(X_train,Y_train)

training_data_prediction = model.predict(X_train)

r2_score = metrics.r2_score(Y_train,training_data_prediction)
print("R2 Score IS:",r2_score)
mse = metrics.mean_squared_error(Y_train,training_data_prediction)
print("Mean Squared Error:",mse)

plt.scatter(Y_train,training_data_prediction)
plt.xlabel("Actual price")
plt.ylabel("Predicted Price")
plt.title("Actual price VS Predicted Price")
plt.show()

testing_data_prediction =  model.predict(X_test)

r2_score = metrics.r2_score(Y_test,testing_data_prediction)
print("R2 Score IS:",r2_score)
mse = metrics.mean_squared_error(Y_test,testing_data_prediction)
print("Mean Squared Error:",mse)

plt.scatter(Y_test,testing_data_prediction)
plt.xlabel("Actual Price")
plt.ylabel("Predicted Price")
plt.title("Actual Price vs Predicted price")
plt.show()

